# Activity - 1

import random
import math
import datetime

# Using random module to generate a random number
random_number = random.randint(1, 100)
print("Random number between 1 and 100:", random_number)

# Using math module to calculate square root
num = 16
sqrt_num = math.sqrt(num)
print(f"Square root of {num} is {sqrt_num}")

# Using datetime module to get the current date and time
current_datetime = datetime.datetime.now()
print("Current date and time:", current_datetime)

# Output:
# Random number between 1 and 100: 42
# Square root of 16 is 4.0
# Current date and time: 2025-05-29 12:34:56.789012





