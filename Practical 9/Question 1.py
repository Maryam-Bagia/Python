my_set = {1, 2, 3}

# Add an element to the set
my_set.add(4)

# Remove an element from the set
my_set.remove(2)

# Get the length of the set
set_length = len(my_set)

print("Updated set:", my_set)
print("Length of the set:", set_length)

# Output:
# Updated set: {1, 3, 4}
# Length of the set: 3


