my_tuple = (1, 2, 3, 4, 5, 3, 3)

# Length of the tuple
print("Length of the tuple:", len(my_tuple))

# Maximum value in the tuple
print("Maximum value in the tuple:", max(my_tuple))

# Count of an element in the tuple
element = 3
print(f"Count of {element} in the tuple:", my_tuple.count(element))

# Index of an element in the tuple
print(f"Index of {element} in the tuple:", my_tuple.index(element))

# Output:
# Length of the tuple: 7
# Maximum value in the tuple: 5
# Count of 3 in the tuple: 3
# Index of 3 in the tuple: 2



