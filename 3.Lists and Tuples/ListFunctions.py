# list.sort()

marks = [94.4, 87.2, 67.7, 84.4, 99.9]

marks.sort()                             # ascending      
print(marks)


# list.sort(reverse = True)

marks = [94.4, 87.2, 67.7, 84.4, 99.9]

marks.sort(reverse = True)               # descending
print(marks)


# list.reverse()

marks = [94.4, 87.2, 67.7, 84.4, 99.9]

marks.reverse()
print(marks)


# list.insert(index , element)

marks = [94.4, 87.2, 67.7, 84.4, 99.9]

marks.insert(3,78.2)
