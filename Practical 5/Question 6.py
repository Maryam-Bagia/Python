x1 = float(input("Enter x1: "))
y1 = float(input("Enter y1: "))
x2 = float(input("Enter x2: "))
y2 = float(input("Enter y2: "))

slope = (y2 - y1) / (x2 - x1)

print(f"Slope of the line: {slope}")

# Output:
# Enter x1: 1
# Enter y1: 2
# Enter x2: 3
# Enter y2: 4
# Slope of the line: 1.0

